-- 2. blog_posts 테이블에 content 컬럼 추가 (이미 있으면 무시)
ALTER TABLE blog_posts ADD COLUMN IF NOT EXISTS content TEXT DEFAULT '';

-- ============================================
-- 3. increment_views RPC 함수 생성
-- (블로그 상세 페이지 조회 시 조회수 +1)
-- ============================================
CREATE OR REPLACE FUNCTION increment_views(post_id BIGINT)
RETURNS void AS $$
BEGIN
  UPDATE blog_posts
  SET views = views + 1
  WHERE id = post_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

